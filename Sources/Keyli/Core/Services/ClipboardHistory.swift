import AppKit

public struct ClipboardItem: Identifiable, Equatable {
    public let id: UUID
    public var text: String
    public var date: Date

    public init(id: UUID = UUID(), text: String, date: Date = Date()) {
        self.id = id
        self.text = text
        self.date = date
    }
}

public final class ClipboardHistory: ObservableObject {
    public static let shared = ClipboardHistory()

    public static let maxItems = 30
    public static let maxLength = 20_000

    @Published public private(set) var items: [ClipboardItem] = []

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.apple.securetext"
    ]

    private init() {}

    public var isRunning: Bool { timer != nil }

    public func applyConfig() {
        if ConfigStore.shared.config.clipboardHistoryEnabled {
            start()
        } else {
            stop()
            clear()
        }
    }

    private func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
    }

    public static func shouldRecord(types: [String]) -> Bool {
        !types.contains { skippedTypes.contains($0) }
    }

    public static func inserting(_ text: String, into items: [ClipboardItem], date: Date = Date(), limit: Int = maxItems) -> [ClipboardItem] {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, text.count <= maxLength else { return items }
        var next = items.filter { $0.text != text }
        next.insert(ClipboardItem(text: text, date: date), at: 0)
        return Array(next.prefix(limit))
    }

    public static func matching(_ items: [ClipboardItem], query: String) -> [ClipboardItem] {
        let trimmed = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return items }
        return items.filter { $0.text.localizedCaseInsensitiveContains(trimmed) }
    }

    func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = (pasteboard.types ?? []).map { $0.rawValue }
        guard Self.shouldRecord(types: types), let text = pasteboard.string(forType: .string) else { return }
        let next = Self.inserting(text, into: items)
        if next != items { items = next }
    }

    public func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
    }

    public func clear() {
        if !items.isEmpty { items.removeAll() }
    }

    public func paste(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        items = Self.inserting(item.text, into: items)

        let layout = KeyboardState.shared.currentLayout
        let vKey = layout.keys.first { $0.kind == .character && $0.labels.defaultLabel.lowercased() == "v" && !KeyboardLayoutManager.isKeypadKey($0) }
            ?? KeyboardKey(id: "k_9", keyCode: 9, kind: .character, unitFrame: KeyUnitFrame(x: 0, y: 0), labels: KeyLabels(defaultLabel: "v"))
        let state = KeyboardState()
        state.isCommandActive = true
        KeyboardInputDispatcher.shared.dispatchKey(vKey, state: state)
        KeySoundEngine.shared.tap(vKey.keyCode)
        WordSuggestions.shared.reset()
    }
}
